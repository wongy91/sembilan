let current = 'en';

export function setLang(lang) {
  current = STRINGS[lang] ? lang : 'en';
}

export function getLang() {
  return current;
}

export function tr(lang, key, vars = {}) {
  const s = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

export function t(key, vars) {
  return tr(current, key, vars);
}

export function fmtDistance(m) {
  if (m < 100) return `${Math.max(0, Math.round(m / 10) * 10)} m`;
  if (m < 950) return `${Math.round(m / 50) * 50} m`;
  const km = m / 1000;
  return `${km < 10 ? km.toFixed(1) : Math.round(km)} km`;
}

export function fmtDuration(seconds, lang = current) {
  const mins = Math.max(1, Math.round(seconds / 60));
  if (mins < 60) return tr(lang, 'minutes', { m: mins });
  const h = Math.floor(mins / 60);
  const m = mins % 60;
  return m ? tr(lang, 'hours', { h, m }) : tr(lang, 'hoursOnly', { h });
}

export function fmtClock(date, lang = current) {
  return new Intl.DateTimeFormat(lang === 'en' ? 'en-MY' : 'ms-MY', { hour: 'numeric', minute: '2-digit' }).format(date);
}

export function fmtAgo(ms, lang = current) {
  const mins = Math.max(1, Math.round(ms / 60000));
  const d = mins < 60 ? tr(lang, 'agoMinutes', { n: mins }) : tr(lang, 'agoHours', { n: Math.round(mins / 60) });
  return tr(lang, 'ago', { d });
}
